import { FileText, Calendar, Pill, User, Printer } from 'lucide-react'

const PrescriptionCard = ({ prescription, showPrint = true }) => {
  const dateStr = new Date(prescription.created_at).toLocaleDateString('en-PK', {
    year: 'numeric', month: 'long', day: 'numeric'
  })

  const handlePrint = () => {
    const printContent = `
      <html>
      <head>
        <title>Prescription - ${prescription.patient_name}</title>
        <style>
          body { font-family: Arial, sans-serif; padding: 40px; color: #1e293b; }
          .header { border-bottom: 3px solid #1d4ed8; padding-bottom: 20px; margin-bottom: 30px; }
          .header h1 { color: #1d4ed8; font-size: 28px; margin: 0; }
          .header p { margin: 5px 0; color: #64748b; }
          .section { margin-bottom: 24px; }
          .section h3 { color: #0f766e; border-bottom: 1px solid #e2e8f0; padding-bottom: 8px; margin-bottom: 12px; }
          .medicine { background: #f8fafc; padding: 12px; border-radius: 8px; margin-bottom: 10px; border-left: 4px solid #1d4ed8; }
          .medicine h4 { margin: 0 0 6px 0; }
          .medicine p { margin: 2px 0; color: #64748b; font-size: 14px; }
          .footer { margin-top: 40px; border-top: 1px solid #e2e8f0; padding-top: 20px; color: #94a3b8; font-size: 12px; }
          .info-grid { display: grid; grid-template-columns: 1fr 1fr; gap: 16px; }
          .info-item label { font-weight: bold; color: #475569; display: block; margin-bottom: 4px; }
        </style>
      </head>
      <body>
        <div class="header">
          <h1>Nucura Prescription</h1>
          <p>Date: ${dateStr}</p>
        </div>
        <div class="section info-grid">
          <div class="info-item"><label>Patient</label>${prescription.patient_name}</div>
          <div class="info-item"><label>Doctor</label>${prescription.doctor_name}</div>
        </div>
        <div class="section"><h3>Diagnosis</h3><p>${prescription.diagnosis}</p></div>
        <div class="section">
          <h3>Prescribed Medicines</h3>
          ${prescription.medicines?.map(med => `
            <div class="medicine">
              <h4>${med.name} - ${med.dosage}</h4>
              <p>Frequency: ${med.frequency}</p>
              <p>Duration: ${med.duration}</p>
            </div>`).join('')}
        </div>
        ${prescription.instructions ? `<div class="section"><h3>Special Instructions</h3><p>${prescription.instructions}</p></div>` : ''}
        ${prescription.follow_up_date ? `<div class="section"><h3>Follow-up Date</h3><p>${prescription.follow_up_date}</p></div>` : ''}
        <div class="footer"><p>Generated by Nucura Healthcare Platform</p></div>
      </body>
      </html>`
    const printWindow = window.open('', '_blank')
    printWindow.document.write(printContent)
    printWindow.document.close()
    printWindow.print()
  }

  return (
    <div className="bg-white rounded-2xl border border-slate-100 shadow-sm overflow-hidden hover:shadow-md transition-shadow">
      <div className="bg-gradient-to-r from-blue-700 to-teal-700 px-5 py-3.5 flex items-center justify-between">
        <div className="flex items-center space-x-3">
          <FileText className="h-5 w-5 text-white" />
          <div>
            <h3 className="font-semibold text-white text-sm">Prescription</h3>
            <p className="text-blue-100 text-xs">{dateStr}</p>
          </div>
        </div>
        {showPrint && (
          <button onClick={handlePrint}
            className="flex items-center bg-white text-blue-700 px-3 py-1.5 rounded-lg text-xs font-medium hover:bg-blue-50 transition">
            <Printer className="h-3 w-3 mr-1.5" />Print
          </button>
        )}
      </div>

      <div className="p-5">
        <div className="grid grid-cols-2 gap-4 mb-4">
          {[['Patient', prescription.patient_name], ['Doctor', prescription.doctor_name]].map(([label, value]) => (
            <div key={label} className="flex items-center space-x-2">
              <User className="h-4 w-4 text-blue-500" />
              <div>
                <p className="text-xs text-slate-400">{label}</p>
                <p className="font-semibold text-sm text-slate-800">{value}</p>
              </div>
            </div>
          ))}
        </div>

        <div className="mb-4 p-3 bg-blue-50 rounded-xl border border-blue-100">
          <p className="text-xs font-semibold text-blue-700 mb-1">DIAGNOSIS</p>
          <p className="text-slate-800 text-sm">{prescription.diagnosis}</p>
        </div>

        <div className="mb-4">
          <p className="text-xs font-semibold text-slate-500 mb-2 flex items-center">
            <Pill className="h-3 w-3 mr-1" />PRESCRIBED MEDICINES
          </p>
          <div className="space-y-2">
            {prescription.medicines?.map((med, idx) => (
              <div key={idx} className="p-3 bg-slate-50 rounded-xl border border-slate-100">
                <div className="flex items-center justify-between mb-1">
                  <span className="font-semibold text-sm text-slate-800">{med.name}</span>
                  <span className="text-xs bg-teal-50 text-teal-700 border border-teal-100 px-2 py-0.5 rounded-lg">{med.dosage}</span>
                </div>
                <div className="flex items-center space-x-4 text-xs text-slate-500">
                  <span>{med.frequency}</span>
                  <span>{med.duration}</span>
                </div>
              </div>
            ))}
          </div>
        </div>

        {prescription.instructions && (
          <div className="mb-4 p-3 bg-amber-50 rounded-xl border border-amber-100">
            <p className="text-xs font-semibold text-amber-700 mb-1">SPECIAL INSTRUCTIONS</p>
            <p className="text-slate-700 text-sm">{prescription.instructions}</p>
          </div>
        )}

        {prescription.follow_up_date && (
          <div className="flex items-center space-x-2 p-3 bg-teal-50 rounded-xl border border-teal-100">
            <Calendar className="h-4 w-4 text-teal-600" />
            <div>
              <p className="text-xs font-semibold text-teal-700">FOLLOW-UP DATE</p>
              <p className="text-slate-700 text-sm">{prescription.follow_up_date}</p>
            </div>
          </div>
        )}
      </div>
    </div>
  )
}

export default PrescriptionCard